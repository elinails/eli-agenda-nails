-- ============================================================================
-- 1 · TABLA: billeteras_salones
-- ============================================================================
-- Un registro por salon (salon_id UNIQUE).
-- saldo_actual es la cantidad de Elima Points que tiene el salon.
-- ============================================================================

create table if not exists public.billeteras_salones (
    id uuid not null generated by default as identity,
    salon_id uuid not null unique,
    saldo_actual numeric not null default 0,
    creado_en timestamptz not null default now(),
    constraint billeteras_salones_pkey primary key (id)
);

comment on table public.billeteras_salones is 'Billetera interna del salon: saldo de Elima Points';
comment on column public.billeteras_salones.salon_id is 'FK a la tabla salones (unique, un registro por salon)';
comment on column public.billeteras_salones.saldo_actual is 'Saldo en puntos (1 punto = $1 pesos)';


-- Índice para búsquedas por salon
create index if not exists idx_billeteras_salones_salon_id
    on public.billeteras_salones (salon_id);


