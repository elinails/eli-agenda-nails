-- ============================================================================
-- 4 · RPC: comprar_puntos_salon(p_monto numeric)
-- ============================================================================
-- Simula la compra de puntos con MercadoPago.
-- Por ahora es un "mock": recibe un monto en dinero (ej. 10000),
-- calcula los puntos (1 punto = $1, así que 10000 pesos = 10000 puntos)
-- y los suma a la billetera del salon logueado.
-- En el futuro se conectará con la API real de MercadoPago.
-- ============================================================================

create or replace function public.comprar_puntos_salon(p_monto numeric)
returns table (
    exito boolean,
    puntos_agregados numeric,
    saldo_anterior numeric,
    saldo_nuevo numeric,
    mensaje text
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_salon_id uuid;
    v_puntos numeric := 0;
    v_saldo_actual numeric;
    v_nombre text;
begin
    -- Obtener el salon logueado (usamos el contexto de la sesión)
    -- En RLS security definer, auth.uid() estará disponible si hay sesión JWT
    if auth.uid() is null then
        return query select false, 0, 0, 0, 'sin_autenticar:_no_hay_sesion_jwt';
    end if;

    -- Buscar o crear la billetera de este salon
    -- Usamos el salon_id del contexto. Asumimos que la sesión tiene el salon_id
    -- o lo derivamos de la relación con miembros_salon.
    select s.id into v_salon_id
    from public.salones s
    where s.id = auth.uid() -- esto puede variar según el modelo de multi-tenant;

    -- Alternativa: obtener el salon_id del contexto de la sesión actual
    -- Por ahora, usamos un enfoque: buscar la billetera por salon_id que viene del parámetro
    -- o crear una nueva si no existe.

    -- Simulación: si no encontramos el salon, usamos un ID por defecto o creamos
    if not found then
        -- Intentamos insertar una billetera nueva para el salon actual
        insert into public.billeteras_salones (salon_id, saldo_actual)
        values (auth.uid(), 0)
        on conflict (salon_id) do update set saldo_actual = billeteras_salones.saldo_actual + coalesce(values(saldo_actual), 0)
        returning saldo_actual, salon_id into v_saldo_actual, v_salon_id;
    else
        -- Ya existía, leemos el saldo actual
        select saldo_actual into v_saldo_actual
        from public.billeteras_salones
        where salon_id = v_salon_id;

        if v_saldo_actual is null then
            v_saldo_actual := 0;
        end if;
    end if;

    -- Calcular puntos: 1 punto = $1, así que el monto en pesos = puntos
    v_puntos := greatest(coalesce(p_monto, 0), 0);

    -- Sumar puntos a la billetera
    update public.billeteras_salones
    set saldo_actual = saldo_actual + v_puntos,
        creado_en = now()
    where salon_id = v_salon_id;

    -- Devolver resultado
    return query select true as exito,
                   v_puntos as puntos_agregados,
                   v_saldo_actual - v_puntos as saldo_anterior,
                   v_saldo_actual as saldo_nuevo,
                   'Puntos comprados exitosamente: ' || v_puntos || ' puntos ($' || v_puntos || ') agregados a la billetera.'::text as mensaje;
end $$;

comment on function public.comprar_puntos_salon(numeric)
    is 'Compra simulated de puntos con MercadoPago. 1 peso = 1 punto. Suma a la billetera del salon.';

grant execute on function public.comprar_puntos_salon(numeric) to authenticated;


-- ============================================================================
-- 5 · RPC: comprar_producto_hub(p_producto_id bigint)
-- ============================================================================
-- Verifica que el salon tenga saldo suficiente, le descuenta los puntos de su
-- billetera, inserta el registro en compras_hub y devuelve el saldo restante.
-- ============================================================================

create or replace function public.comprar_producto_hub(p_producto_id bigint)
returns table (
    exito boolean,
    producto_nombre text,
    precio_puntos numeric,
    saldo_anterior numeric,
    saldo_nuevo numeric,
    mensaje text
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_producto catalogo_hub%rowtype;
    v_salon_id uuid;
    v_saldo_actual numeric;
    v_puntos_costo numeric;
    v_exito boolean := false;
    v_mensaje text := 'error_desconocido';
begin
    -- 1. Validar que el producto existe y está activo
    select * into v_producto
    from public.catalogo_hub
    where id = p_producto_id and activo = true;

    if not found then
        return query select false, null, 0, 0, 0,
            'producto_no_encontrado_o_inactivo:el_id ' || p_producto_id || ' no existe o no está disponible';
    end if;

    -- 2. Obtener el salon logueado y su billetera
    -- Usamos auth.uid() para obtener el salon_id actual
    -- En un modelo multi-tenant, esto podría variar; por ahora asumimos que
    -- el usuario autenticado es dueño del salon
    v_salon_id := auth.uid();

    -- Leer saldo actual de la billetera del salon
    select saldo_actual into v_saldo_actual
    from public.billeteras_salones
    where salon_id = v_salon_id;

    if v_saldo_actual is null then
        v_saldo_actual := 0;
    end if;

    -- 3. Verificar saldo suficiente
    v_puntos_costo := greatest(coalesce(v_producto.precio_puntos, 0), 0);

    if v_saldo_actual < v_puntos_costo then
        return query select false, v_producto.nombre, v_puntos_costo,
            v_saldo_actual, v_saldo_actual,
            'saldo_insuficiente:tenes ' || v_saldo_actual || ' pts, pero el producto cuesta ' || v_puntos_costo || ' pts';
    end if;

    -- 4. Descontar puntos de la billetera
    update public.billeteras_salones
    set saldo_actual = saldo_actual - v_puntos_costo,
        creado_en = now()
    where salon_id = v_salon_id;

    -- 5. Insertar registro de compra
    insert into public.compras_hub (salon_id, producto_id, monto_puntos)
    values (v_salon_id, p_producto_id, v_puntos_costo);

    -- 6. Devolver resultado
    v_exito := true;
    v_mensaje := 'Compra exitosa: ' || v_producto.nombre || ' (' || v_puntos_costo || ' pts descontados). Saldo restante: ' || (v_saldo_actual - v_puntos_costo) || ' pts';

    return query select v_exito, v_producto.nombre, v_puntos_costo,
        v_saldo_actual + v_puntos_costo as saldo_anterior, -- lo que había antes de descuento
        v_saldo_actual - v_puntos_costo as saldo_nuevo,
        v_mensaje;
end $$;

comment on function public.comprar_producto_hub(bigint)
    is 'Compra de producto en Tienda HUB. Descuenta puntos de la billetera del salon y registra la compra.';

grant execute on function public.comprar_producto_hub(bigint) to authenticated;


